"""
Кудитный смеситель (mixer) QAOA.

Для кудита размерности d используется оператор сдвига

        M_i = X_d + X_d^† = sum_a ( |a><a+1| + |a+1><a| )   (кольцо)

В позиционном (one-hot) кодировании подпространству однократного
возбуждения соответствует XY-взаимодействие: на паре кубитов (a, b)

        exp( -i β (X_a X_b + Y_a Y_b) / 2 )

действует на состояниях |...1_a 0_b...>, |...0_a 1_b...> ровно как
двухуровневый поворот

        [[cos β, -i sin β],
         [-i sin β,  cos β]]

а состояния |00> и |11> оставляет неизменными. Поэтому XY-смеситель
не выводит систему из подпространства «ровно один хост на ВМ»: некорректных
результатов измерений на идеальном вычислителе не возникает.

Слагаемые кольца попарно не коммутируют, поэтому экспонента раскладывается
по схеме «чётные рёбра, затем нечётные» (один шаг Троттера). Симулятор и
генератор OpenQASM используют один и тот же порядок рёбер, благодаря чему
результат локальной эмуляции совпадает с результатом запуска схемы на
вычислителях платформы.
"""

from __future__ import annotations


def mixer_edges(dim: int) -> list[tuple[int, int]]:
    """Порядок двухуровневых поворотов для регистра размерности dim."""

    if dim < 2:
        return []

    if dim == 2:
        return [(0, 1)]

    ring = [(a, (a + 1) % dim) for a in range(dim)]

    even = [edge for index, edge in enumerate(ring) if index % 2 == 0]
    odd = [edge for index, edge in enumerate(ring) if index % 2 == 1]

    return even + odd
